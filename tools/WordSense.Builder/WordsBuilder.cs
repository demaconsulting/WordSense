using DemaConsulting.WordSense;

namespace WordSense.Builder;

/// <summary>
///     Builds the legacy word table (every known word with its trained senses) from the corpus. It is the source that
///     <c>bootstrap-forms</c> read once and the oracle of the lexicon tests; it is removed together with the corpus
///     sense files.
/// </summary>
/// <remarks>
///     The table answers every known word with its senses. A lemma that has trained weights answers with its trained
///     senses (in the ordinal order of the sense labels, the order of the trained classes). A form listed in
///     <c>corpus/forms</c> answers only with the senses that its labels name, in the same order and as the same
///     <see cref="LegacyWord"/> instances; a form that names every sense shares the lemma's array. An unknown, repeated
///     or missing label, or a row for the lemma itself that does not name every sense, fails the build. A dictionary
///     word answers with one sense per part of speech and no meaning, in the order of
///     the dictionary (most frequent first); an inflected form generated by <see cref="MorphologyExpander"/> answers with
///     one sense of its base. A trained lemma or form that the dictionary lists with more parts of speech keeps its
///     trained senses first and gains one meaningless sense for each part of speech its labels do not cover, with the
///     word itself as lemma (a form may have several lemmas), so no word and no part of
///     speech of the dictionary is lost. Every word of the dictionary is in the table. Each word of the closed list in
///     <c>corpus/lexicon/auxiliaries.tsv</c> finally gains an <see cref="PartOfSpeech.Auxiliary"/> sense after all of its
///     other senses; its forms are not affected.
/// </remarks>
internal static class WordsBuilder
{
    /// <summary>
    ///     Builds the table.
    /// </summary>
    /// <param name="corpus">The corpus directory.</param>
    /// <returns>The entries by word, in ordinal order.</returns>
    /// <exception cref="InvalidDataException">Thrown when the corpus is inconsistent.</exception>
    public static SortedDictionary<string, LegacyWord[]> Build(string corpus)
    {
        var inventory = SenseInventory.ReadDirectory(Path.Combine(corpus, "senses"));
        var errors = inventory.ValidateRules();
        if (errors.Count > 0)
        {
            throw new InvalidDataException(string.Join(Environment.NewLine, errors));
        }

        var entries = new SortedDictionary<string, LegacyWord[]>(StringComparer.Ordinal);
        var senses = new Dictionary<string, LegacyWord[]>(StringComparer.Ordinal);
        foreach (var lemma in inventory.Rows.Select(r => r.Lemma).Distinct(StringComparer.Ordinal))
        {
            var details = new LemmaEntry(lemma, inventory.DefinitionsOf(lemma), true).Candidates.ToArray();
            senses[lemma] = details;
            entries[lemma] = details;
        }

        // A listed form answers with the senses its labels name, in the order of the lemma's senses; a form that names
        // every sense shares the array of the lemma. The checks list every bad row at once.
        var formsDirectory = Path.Combine(corpus, "forms");
        if (Directory.Exists(formsDirectory))
        {
            var forms = Directory.GetFiles(formsDirectory, "*.tsv").OrderBy(f => f, StringComparer.Ordinal).SelectMany(Corpus.ReadForms).ToList();
            var formErrors = inventory.CheckForms(forms);
            if (formErrors.Count > 0)
            {
                throw new InvalidDataException(string.Join(Environment.NewLine, formErrors));
            }

            foreach (var (form, lemma, labels) in forms)
            {
                if (!senses.TryGetValue(lemma, out var details))
                {
                    continue;
                }

                var indexes = inventory.FormSenseIndexes(lemma, labels);
                entries.TryAdd(form, indexes.Length == details.Length ? details : indexes.Select(i => details[i]).ToArray());
            }
        }

        // Dictionary words: one sense per part of speech
        var lexiconPath = Path.Combine(corpus, "lexicon", "lexicon.tsv");
        var lexicon = File.Exists(lexiconPath) ? LexiconSource.ReadWords(lexiconPath) : [];
        lexicon = LexiconSource.MergeAdditions(lexicon, Path.Combine(corpus, "lexicon", LexiconSource.AdditionsFile));
        var singles = new Dictionary<(string, PartOfSpeech), LegacyWord[]>();
        LegacyWord[] Single(string lemma, PartOfSpeech pos)
        {
            if (!singles.TryGetValue((lemma, pos), out var one))
            {
                singles[(lemma, pos)] = one = [new LegacyWord(lemma, pos, null, null)];
            }

            return one;
        }

        var dictionaryBases = new List<(string Word, ushort Mask, string Letters)>();
        foreach (var (word, mask, letters) in lexicon)
        {
            dictionaryBases.Add((word, mask, letters));
            if (entries.TryGetValue(word, out var trained))
            {
                // The trained senses come first (the weights fix their order); the dictionary adds only the parts of
                // speech the labels do not cover, in dictionary order, without meaning or respelling. The extra is the
                // word's own: its lemma is the word itself (a form may have several lemmas, 'lives' is a verb of
                // 'live' and the plural of 'life'), never the lemma of the trained senses.
                var have = trained.Aggregate(0, (m, d) => m | (1 << (int)d.PartOfSpeech));
                var extras = letters
                    .Select(l => (PartOfSpeech)LexiconSource.Letters.IndexOf(l, StringComparison.Ordinal))
                    .Where(p => (have & (1 << (int)p)) == 0)
                    .Select(p => Single(word, p)[0])
                    .ToArray();
                if (extras.Length > 0)
                {
                    entries[word] = [.. trained, .. extras];
                }

                continue;
            }

            entries[word] = letters
                .Select(l => Single(word, (PartOfSpeech)LexiconSource.Letters.IndexOf(l, StringComparison.Ordinal))[0])
                .ToArray();
        }

        // A trained lemma that the dictionary lacks is a base too
        var lexiconWords = lexicon.Select(l => l.Word).ToHashSet(StringComparer.Ordinal);
        foreach (var lemma in senses.Keys.Where(k => !lexiconWords.Contains(k)))
        {
            var letters = string.Concat(senses[lemma].Select(d => LexiconSource.Letters[(int)d.PartOfSpeech]).Distinct());
            dictionaryBases.Add((lemma, LexiconSource.ToMask(letters, lemma), letters));
        }

        dictionaryBases.Sort((a, b) => string.CompareOrdinal(a.Word, b.Word));

        // A generated form of a trained lemma that has several parts of speech answers with all trained senses (a known
        // limit: the generated form is not restricted to its part of speech); any other generated form has one sense
        // for each of its parts of speech and its base as lemma
        LegacyWord[] Answer(string lemma, IReadOnlyList<PartOfSpeech> pos) =>
            pos.Count > 1 && senses.TryGetValue(lemma, out var trainedSenses) ? trainedSenses : pos.Select(p => Single(lemma, p)[0]).ToArray();

        // Generated forms of the dictionary words
        var enabled = MorphologyExpander.ReadEnabled(Path.Combine(corpus, "lexicon", "morphology.tsv"));
        var irregular = IrregularForms.Read(Path.Combine(corpus, "lexicon"));
        foreach (var (form, details) in MorphologyExpander.Expand(dictionaryBases, entries.ContainsKey, enabled, irregular, Answer))
        {
            entries.TryAdd(form, details);
        }

        // The closed list of auxiliaries gains an Auxiliary sense, appended after every existing sense. This happens after
        // the expansion so that no inflected form (wills, willed, cans) is derived from the auxiliary sense. The arrays are
        // shared between a lemma and its forms, so a new array is stored instead of changing the shared one.
        var auxiliariesPath = Path.Combine(corpus, "lexicon", LexiconSource.AuxiliariesFile);
        if (File.Exists(auxiliariesPath))
        {
            foreach (var word in LexiconSource.ReadAuxiliaries(auxiliariesPath))
            {
                if (!entries.TryGetValue(word, out var existing))
                {
                    throw new InvalidDataException($"{LexiconSource.AuxiliariesFile}: the word '{word}' is not in the word table.");
                }

                if (existing.All(d => d.PartOfSpeech != PartOfSpeech.Auxiliary))
                {
                    entries[word] = [.. existing, Single(existing[0].Lemma, PartOfSpeech.Auxiliary)[0]];
                }
            }
        }

        return entries;
    }
}
